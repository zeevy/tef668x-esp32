#!/usr/bin/env python3
"""Put the web page into the firmware.

`npm run build` in web/ makes one file, web/dist/index.html, with its script
and its styles inside it. This gzips it the same way every time and writes it
into src/net/web_page.h as a byte array, with an ETag made from those bytes,
for web_page.cpp to send as it is. The radio pays the gzipped size once, in
flash, and never unpacks it.

    npm --prefix web run build && python3 tools/web_page.py

--check writes nothing, and fails when the header is not what the page
builds to now, so a change to the page cannot reach a firmware without it.
The header is run through clang-format here, so the format gate passes it.
"""

import gzip
import hashlib
import io
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
PAGE = ROOT / "web" / "dist" / "index.html"
HEADER = ROOT / "src" / "net" / "web_page.h"
# The most the gzipped page may weigh. Every phone and laptop that opens the
# radio fetches it over the radio's Wi-Fi, and a bigger page also takes longer
# to start on a phone; a change that needs more raises this on purpose.
BUDGET = 64 * 1024


def header_text() -> tuple[str, int]:
    raw = PAGE.read_bytes()
    out = io.BytesIO()
    # No time and no name in the gzip header, so the same page gives the
    # same bytes on every machine.
    with gzip.GzipFile(fileobj=out, mode="wb", compresslevel=9, mtime=0, filename="") as gz:
        gz.write(raw)
    data = out.getvalue()
    etag = hashlib.sha256(data).hexdigest()[:16]
    body = ", ".join(str(b) for b in data)
    text = f"""#pragma once

/* Generated by tools/web_page.py from web/dist/index.html. Do not hand edit.
 * The page, {len(raw)} bytes, gzipped to {len(data)}. */

#include <Arduino.h>

/* Quoted, as an ETag header carries it. */
static const char kWebPageEtag[] = "\\"{etag}\\"";

static const uint8_t kWebPageGz[] PROGMEM = {{{body}}};
static const size_t kWebPageGzLen = sizeof(kWebPageGz);
"""
    # The clang-format the format gate found, so the header is laid out as
    # the gate wants it; the first one on the PATH may be another version.
    formatted = subprocess.run(
        [os.environ.get("CLANG_FORMAT", "clang-format"), f"--assume-filename={HEADER}"],
        input=text,
        capture_output=True,
        text=True,
        check=True,
    ).stdout
    return formatted, len(data)


def main() -> int:
    if not PAGE.exists():
        print(f"{PAGE} is not there. Run npm --prefix web run build first.")
        return 1
    text, size = header_text()
    if size > BUDGET:
        print(f"The page gzips to {size} bytes, over its budget of {BUDGET}.")
        return 1
    if "--check" in sys.argv[1:]:
        if not HEADER.exists() or HEADER.read_text() != text:
            print(f"{HEADER.relative_to(ROOT)} is not the page as it builds now. Run python3 tools/web_page.py and commit it.")
            return 1
        print(f"{HEADER.relative_to(ROOT)} matches the page.")
        return 0
    HEADER.write_text(text)
    print(f"Wrote {HEADER.relative_to(ROOT)}.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
